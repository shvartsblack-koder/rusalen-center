//
// Правила модели:
// 1. Ни один компонент отображения не хранит фактические параметры
//    программ (название, часы, статус, цену, документ, преподавателей),
//    если они есть здесь. Компоненты отвечают только за отображение.
// 2. Неподтверждённые значения хранятся как null и выводятся на сайте
//    как «уточняется». Заполнять их предположениями запрещено.
//    Исключение — часы направлений в подготовке: это предварительные
//    оценки базовой матрицы (dpo/matrixData), проставленные условно
//    до подтверждения учебных планов.
// 3. Цены, даты и параметры конкретных наборов живут в cohorts
//    и выводятся только из подтверждённых данных.
// 4. Внутренние AiProf/RSK и служебная матрица в публичной модели
//    не хранятся и на сайт не выводятся.
// 5. Учебные модули и связи карты живут во внутреннем слое
//    (dpo/matrixData) и синхронизируются с этой моделью через
//    eduId: подтверждённые факты программ читаются отсюда.
// ============================================================

